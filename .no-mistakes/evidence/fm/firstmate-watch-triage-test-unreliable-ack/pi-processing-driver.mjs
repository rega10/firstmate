import {createServer} from 'node:http';
import {spawnSync} from 'node:child_process';
import {mkdirSync, writeFileSync, readFileSync, existsSync, copyFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const root=process.cwd(), lab=`${root}/.test-phase-temp/pi-processing-lab`, agentDir=`${lab}/agent`;
mkdirSync(agentDir,{recursive:true});
process.env.FM_HOME=lab;
process.env.PI_CODING_AGENT_DIR=agentDir;
process.env.PI_OFFLINE='1';
const requests=[];
const server=createServer(async(req,res)=>{
 let data=''; for await(const chunk of req)data+=chunk;
 requests.push(JSON.parse(data));
 res.writeHead(200,{'Content-Type':'text/event-stream'});
 const chunk={id:'local',object:'chat.completion.chunk',created:1,model:'local',choices:[{index:0,delta:{role:'assistant',content:'Local endpoint response.'},finish_reason:null}]};
 res.write(`data: ${JSON.stringify(chunk)}\n\n`);
 res.write(`data: ${JSON.stringify({...chunk,choices:[{index:0,delta:{},finish_reason:'stop'}]})}\n\n`);
 res.end('data: [DONE]\n\n');
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const port=server.address().port;
writeFileSync(`${agentDir}/models.json`,JSON.stringify({providers:{'isolated-endpoint':{baseUrl:`http://127.0.0.1:${port}/v1`,api:'openai-completions',apiKey:'local-fixture',models:[{id:'local',contextWindow:128000,maxTokens:1024}]}}}));
writeFileSync(`${agentDir}/settings.json`,JSON.stringify({defaultProvider:'isolated-endpoint',defaultModel:'local'}));
writeFileSync(`${lab}/state/.lock`,`${process.pid}\n`);
const packageRoot=`${root}/.test-phase-temp/pi-runtime/node_modules/@earendil-works/pi-coding-agent`;
const {createAgentSession,DefaultResourceLoader,SessionManager,ModelRuntime}=await import(pathToFileURL(`${packageRoot}/dist/index.js`));
const events=[], errors=[]; let extensionApi;
const loader=new DefaultResourceLoader({cwd:lab,agentDir,noExtensions:true,noSkills:true,noPromptTemplates:true,noThemes:true,noContextFiles:true,additionalExtensionPaths:[`${root}/.pi/extensions/fm-branch-supervision.ts`],extensionFactories:[{name:'event-observer',factory:(pi)=>{extensionApi=pi; pi.on('before_agent_start',event=>{events.push(event);if(event.message?.customType==='fm-branch-process'){writeFileSync(`${lab}/state/.afk-contract`,'{}\n');console.log('AWAY_RECORD appeared before processing context');}console.log('PI_EVENT',JSON.stringify({type:event.type,messageType:event.messageType,prompt:event.prompt,message:event.message}));});}}]});
await loader.reload();
const resourceErrors=loader.getExtensions().errors;
if(resourceErrors.length) throw Error(JSON.stringify(resourceErrors));
const runtime=await ModelRuntime.create({authPath:`${agentDir}/auth.json`,modelsPath:`${agentDir}/models.json`});
const {session}=await createAgentSession({cwd:lab,agentDir,modelRuntime:runtime,resourceLoader:loader,sessionManager:SessionManager.create(lab,`${lab}/sessions`),tools:[]});
session.extensionRunner.onError(error=>{errors.push(error);console.log('EXTENSION_ERROR',JSON.stringify(error));});
await session.bindExtensions({mode:'rpc',abortHandler:()=>{void session.abort();}});
try{
 const appended=spawnSync('bash',[`${root}/bin/fm-branch-outcome.sh`,'append','--task','fleet','--verdict','captain','--summary','ISOLATED_PROCESSING_SENTINEL'],{env:process.env,encoding:'utf8'});
 if(appended.status!==0)throw Error(appended.stderr);
 await session.prompt('Collect the isolated pending outcome.');
 for(let i=0;i<100&&!events.some(event=>event.message?.customType==='fm-branch-process');i++)await new Promise(r=>setTimeout(r,20));
 if(!events.some(event=>event.message?.customType==='fm-branch-process'))throw Error('Pi did not start a processing custom turn');
 while(session.isStreaming)await new Promise(r=>setTimeout(r,20));
 const requestsBefore=requests.length;
 await session.sendCustomMessage({customType:'extension-note',content:'UNRELATED_CUSTOM_SENTINEL',display:false},{triggerTurn:true});
 console.log('PROVIDER_REQUESTS_BEFORE_UNRELATED',requestsBefore,'AFTER',requests.length);
 copyFileSync(session.sessionFile,`${process.env.EVIDENCE_DIR}/pi-processing-session.jsonl`);
 if(requestsBefore!==1)throw Error('the processing custom turn contacted the provider after the away record appeared');
 if(requests.length!==requestsBefore+1)throw Error('unrelated custom turn retained processing abort state');
 if(errors.length)throw Error('extension errors');
 console.log('VERIFIED processing custom turn aborts after an away record appears; the next unrelated custom turn reaches the provider.');
}finally{session.dispose();server.closeAllConnections();server.close();}
